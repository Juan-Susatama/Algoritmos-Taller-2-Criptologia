    print(f"   - Bits diferentes en ciphertext: {bits_diff_clave} de {total_bits_cifrado} bits ({porcentaje_clave:.2f}%)\n")

    # --- Avalancha de Mensaje ---
    # Invertimos el bit 0 del mensaje original
    mensaje_modificado = flip_bit(mensaje_bytes, 0)
