    # --- Avalancha de Clave ---
    # Invertimos el bit 0 de la clave
    key_modificada = flip_bit(key, 0)
    cifrador_key_mod = CSSCipher(key_modificada)
    cifrado_key_mod = cifrador_key_mod.crypt(mensaje_bytes)

    bits_diff_clave = hamming_distance(cifrado, cifrado_key_mod)
    total_bits_cifrado = len(cifrado) * 8
